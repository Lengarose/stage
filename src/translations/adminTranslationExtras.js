function nestKeys(flat, valueFn) {
  const root = {};
  for (const full of flat) {
    const parts = full.replace(/^admin\./, "").split(".");
    let cur = root;
    for (let i = 0; i < parts.length - 1; i++) {
      cur[parts[i]] = cur[parts[i]] || {};
      cur = cur[parts[i]];
    }
    cur[parts[parts.length - 1]] = valueFn(full);
  }
  return root;
}

