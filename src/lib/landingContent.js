export function landingContent(value) {
  let raw = value;
  if (typeof raw === 'string') { try { raw = JSON.parse(raw); } catch { raw = {}; } }
  raw = raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : {};
  const image = item => ({url: typeof item?.url === 'string' && (/^https?:\/\//i.test(item.url) || /^\/(?!\/)/.test(item.url)) ? item.url : '', position: /^\d{1,3}% \d{1,3}%$/.test(item?.position) ? item.position : '50% 50%', zoom: Math.max(100, Math.min(500, Number(item?.zoom) || 100))});
  return {copy: Object.fromEntries(LANDING_COPY_GROUPS.flatMap(group => group.fields).map(field => [field.key, typeof raw.copy?.[field.key] === 'string' ? raw.copy[field.key].slice(0,5000) : ''])), slides: Array.from({length:6},(_,i)=>image(raw.slides?.[i])), interval: Math.max(3,Math.min(30,Number(raw.interval)||4.5)), platform_image: image(raw.platform_image), logo_image: image(raw.logo_image)};
}
export function landingTranslate(content, fallback) {
  return (key, params, extra) => {
    const text = content.copy[key];
    if (!text?.trim()) return fallback(key, params, extra);
    const values = typeof params === 'object' && params ? params : extra || {};
    return Object.entries(values).reduce((result,[name,value])=>result.replaceAll(`{{${name}}}`,String(value)).replaceAll(`{${name}}`,String(value)),text);
  };
}
