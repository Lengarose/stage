#!/usr/bin/env node
/**
 * Scans src/translations/packs/*.json and regenerates localePackRegistry.js
 * with static JSON imports for Vite + Node (import attributes).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const packsDir = path.join(root, "src/translations/packs");
const outFile = path.join(root, "src/translations/localePackRegistry.js");

const SECTIONS = ["commonPages", "matchFlow", "competitionFlow", "tournamentDetail"];
const SKIP_LANGS = new Set(["en", "fr"]);

const files = fs.readdirSync(packsDir).filter((f) => f.endsWith(".json"));
const found = [];

for (const file of files) {
  const m = file.match(/^([a-z]{2})\.(commonPages|matchFlow|competitionFlow|tournamentDetail)\.json$/);
  if (!m) continue;
  const [, lang, section] = m;
  if (SKIP_LANGS.has(lang)) continue;
  found.push({ lang, section, file, varName: `${lang}_${section}` });
}

found.sort((a, b) => a.lang.localeCompare(b.lang) || a.section.localeCompare(b.section));

const imports = found
  .map((f) => `import ${f.varName} from "./packs/${f.file}" with { type: "json" };`)
  .join("\n");

const byLang = {};
for (const f of found) {
  if (!byLang[f.lang]) byLang[f.lang] = {};
  byLang[f.lang][f.section] = f.varName;
}

const body = Object.entries(byLang)
  .map(([lang, sections]) => {
    const lines = Object.entries(sections)
      .map(([section, varName]) => `    ${section}: ${varName},`)
      .join("\n");
    return `  ${lang}: {\n${lines}\n  },`;
  })
  .join("\n");

const source = `/** Auto-generated by scripts/generate-locale-registry.mjs — do not edit by hand. */
${imports}

export const SECTION_PACKS = {
${body}
};
`;

fs.writeFileSync(outFile, source);
console.log(`Wrote ${outFile} with ${found.length} packs:`);
for (const f of found) console.log(`  - ${f.lang}.${f.section}`);
